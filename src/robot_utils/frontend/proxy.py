"""The robot's port-80 proxy: an nginx config, run as the systemd user unit robot-proxy.service.

One origin serves everything (docs/nodes.md):

    http://<robot>/                     -> the landing page   <runtime dir>/robot/frontend.sock
    http://<robot>/nodes/<name>/<path>  -> <path> on           <runtime dir>/robot/<name>.sock

The node rule is a wildcard: the instance name is taken from the URL, so starting a new
instance (``--name``) needs no proxy change or reload. If an instance's socket does not answer,
nginx hands the request to the landing page's own ``/nodes/`` route, which reports it as a JSON
502 (and reaches nodes on other machines). Streams pass straight through: no buffering in either
direction, no gzip, HTTP/1.1 keep-alive to the sockets, day-long timeouts (SSE, MJPEG, record
streams). nginx runs as the user: pid, logs and temp files live under ``state_dir``.

    python -m robot_utils.frontend.proxy --conf-dir ~/.config/robot_utils/nginx \\
        --state-dir ~/.local/state/robot_utils/nginx      # writes nginx.conf (install.sh does this)
"""
from __future__ import annotations

import argparse
from pathlib import Path

from ..nodes.common.serve import socket_dir

NAME_RE = "[A-Za-z0-9_.-]+"   # = serve.NAME

PROXY_HEADERS = """\
proxy_http_version 1.1;
proxy_set_header Connection "";
proxy_set_header Host $host;
proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
proxy_set_header X-Forwarded-Proto $scheme;
proxy_buffering off;
proxy_request_buffering off;
proxy_cache off;
proxy_read_timeout 1d;
proxy_send_timeout 1d;
"""


def render(*, sockets: Path, state_dir: Path, port: int = 80) -> str:
    """nginx.conf text. ``sockets``: the directory of the instances' unix sockets."""
    sock = lambda name: f"{sockets}/{name}.sock"   # noqa: E731
    tmp = state_dir / "tmp"
    return f"""\
# Generated by robot_utils (python -m robot_utils.frontend.proxy; install.sh). Do not edit:
# re-running install.sh rewrites it. Docs: docs/nodes.md.
worker_processes 1;
pid {state_dir}/nginx.pid;
error_log {state_dir}/error.log warn;

events {{
    worker_connections 1024;
}}

http {{
    access_log off;
    client_body_temp_path {tmp}/body;
    proxy_temp_path {tmp}/proxy;
    fastcgi_temp_path {tmp}/fastcgi;
    uwsgi_temp_path {tmp}/uwsgi;
    scgi_temp_path {tmp}/scgi;
    default_type application/octet-stream;
    server_tokens off;
    gzip off;
    client_max_body_size 64m;
    send_timeout 1d;

    server {{
        listen {port} default_server;
        listen [::]:{port} default_server;

        # /nodes/<name> -> /nodes/<name>/ (node pages use relative URLs)
        location ~ ^/nodes/(?<node>{NAME_RE})$ {{
            return 301 /nodes/$node/$is_args$args;
        }}

        # /nodes/<name>/<path> -> <path> on the instance's own socket (wildcard: no reload
        # needed for new instances). The node uses X-Forwarded-Prefix as its root path.
        location ~ ^/nodes/(?<node>{NAME_RE})(?<rest>/.*)$ {{
{_indent(PROXY_HEADERS, 12)}            proxy_set_header X-Forwarded-Prefix /nodes/$node;
            proxy_pass http://unix:{sockets}/$node.sock:$rest$is_args$args;
            # socket missing / not answering: let the landing page answer (JSON 502, remote nodes)
            error_page 502 504 = @frontend;
        }}

        location / {{
{_indent(PROXY_HEADERS, 12)}            proxy_pass http://unix:{sock("frontend")};
        }}

        location @frontend {{
{_indent(PROXY_HEADERS, 12)}            proxy_pass http://unix:{sock("frontend")};
        }}
    }}
}}
"""


def _indent(text: str, n: int) -> str:
    return "".join(" " * n + line + "\n" for line in text.splitlines())


def write(conf_dir: Path, state_dir: Path, port: int = 80, sockets: Path | None = None) -> Path:
    conf_dir.mkdir(parents=True, exist_ok=True)
    for sub in ("body", "proxy", "fastcgi", "uwsgi", "scgi"):
        (state_dir / "tmp" / sub).mkdir(parents=True, exist_ok=True)
    path = conf_dir / "nginx.conf"
    path.write_text(render(sockets=sockets or socket_dir(), state_dir=state_dir, port=port))
    return path


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m robot_utils.frontend.proxy", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--conf-dir", type=Path, default=Path("~/.config/robot_utils/nginx").expanduser())
    ap.add_argument("--state-dir", type=Path, default=Path("~/.local/state/robot_utils/nginx").expanduser())
    ap.add_argument("--port", type=int, default=80)
    ap.add_argument("--sockets", type=Path, default=None, help="socket directory (default: the nodes')")
    args = ap.parse_args(argv)
    print(write(args.conf_dir, args.state_dir, args.port, args.sockets))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
