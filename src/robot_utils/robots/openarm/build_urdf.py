"""Generate the OpenArm v2.0 arm URDFs (left and right): Enactic's arm (enactic/openarm_description) with Anvil's
joint ranges and Anvil's Customizable Gripper (README.md).

    python -m robot_utils.robots.openarm.build_urdf /path/to/openarm_description   # a checkout of UPSTREAM_COMMIT

What it does (no xacro needed: upstream ships an expanded example, ``assets/robot/openarm_v2.0/urdf/example/v2.urdf``,
autogenerated by xacro from ``openarm_v20.urdf.xacro``, the ``presets/v2/default_bimanual.yaml`` robot):

- takes each arm's chain as upstream builds it, **left and right as they are** (upstream's left arm is its own
  reflection of the right one, with its own joint axes; nothing is mirrored here): ``base_link``, ``link1``..``link6``
  with their inertials (masses, COMs, inertias: Enactic's), the joints ``joint1``..``joint7`` with their origins and
  axes, prefixes stripped;
- joint 7's child, upstream the pinch gripper's base (the empty ``link7`` collapsed into it), becomes ``link7``: a
  massless flange (a tiny inertia, as simulators need one) carrying the flange adapter (``ADAPTER``, a box). Upstream's
  pinch gripper is removed;
- **the joint ranges** (``LIMITS``): J1 Enactic's window; J2-J7 the Anvil OpenArm 2.0's, including J6 (left
  -45..+70 deg, right -70..+45); velocities Anvil's (efforts: Anvil's = Enactic's). The numbers carry over unchanged
  because Anvil's and Enactic's joint origins, axes and signs coincide at q = 0 (FK, 1e-9 m; test_openarm.py);
- **Anvil's Customizable Gripper** (``gripper/anvil_gripper_<side>.urdf``, robots/grippers.py ``anvil``): ``end_link``
  (at the fingertips, midway between the jaws, x out of the fingertips, z toward the wrist camera) with the hand's
  visual meshes, mass and inertia and the gripper type's collision boxes, ``finger_left`` (prismatic along end_link y,
  0..0.05 m) and ``finger_right`` (its mimic, -1). Mounted by ``end_joint`` ``END_FROM_J7`` below the joint-7 axis,
  x along the flange's -z: where Anvil's model puts end_link relative to joint 7;
- meshes: upstream's collision STLs (the visual meshes are COLLADA, which MuJoCo cannot load), for both the visual
  and the collision geometry; copied to ``meshes/collision/``. Upstream's left arm reuses the right arm's STLs mirrored
  by a mesh ``scale`` (``1 -1 1`` on base_link, link1, link2, link5, link6): that scale is baked into a copy of its own
  (``left_<name>.stl``: vertices and normals scaled, triangle winding reversed when the scale mirrors), so every
  consumer gets plain meshes (a negative scale flips the winding, which not every loader handles). The gripper's
  meshes are in ``gripper/meshes/``.
"""
from __future__ import annotations

import math
import shutil
import struct
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
UPSTREAM_COMMIT = "c710e19a4789ff04bae6ae9a04b1aa39130b649f"
EXAMPLE = "assets/robot/openarm_v2.0/urdf/example/v2.urdf"
LINKS = ["base_link", "link1", "link2", "link3", "link4", "link5", "link6"]
GRIPPER = HERE / "gripper"
# end_link below the joint-7 axis (m), along the flange's normal: Anvil's model (the fine tips' far end; its hand on its
# link7 flange). Anvil's link7 frame and Enactic's differ by a constant rotation (the joint axes coincide), and in
# Enactic's frame Anvil's end_link is at (0, 0, -0.2026) with x along -z, the orientation Enactic's end_link had: FK at
# q = 0 and at random q (3e-9 m, 4e-6 rad: Anvil's 1.5708 roundings), checked when this model was made.
END_FROM_J7 = 0.2026
# The flange adapter on link7 (a box, visual and collision; no mass of its own: an ESTIMATE of Anvil's part, which has
# no public CAD here): it fills the gap between Enactic's wrist housing (link6's mesh ends 28.5 mm below the joint-7
# axis) and the top of Anvil's hand (51.1 mm below it), which Anvil's own link7 bridges. Centre and size in link7, m.
ADAPTER = ((0.0, 0.0, -0.0398), (0.05, 0.05, 0.0226))
DEG = math.pi / 180
# The joint ranges: (lower, upper) rad and velocity rad/s per joint, each arm in its own joint convention.
# - J1: Enactic's window (right -80..+200 deg, left -200..+80: 200 deg of forward flexion on both), not Anvil's
#   +-140 deg: the window's position is a mounting choice, not a joint property (both span 280 deg, centred 60 deg
#   apart; re-clocking the J1 housing or another mounting plate shifts it), and Enactic's keeps the overhead forward
#   reach, which matters more for human teleop (the owner's choice, 2026-11-25).
# - J2-J7: the Anvil OpenArm 2.0's, as Anvil states them for its arm (the same joints: FK above). They differ from
#   Enactic's upstream values only in rounding but for J6, Anvil's wrist: left -45..+70 deg, right -70..+45 (upstream
#   +-45). The 70 deg side tilts the fingertips toward the wrist camera (end_link +z) on both arms (test_openarm.py).
# - Velocities: Anvil's (10.47 on J1-J2, 3.77 on J3-J4, 12.57 on J5-J7; upstream's 16.755 / 5.4454 / 20.944). The
#   arm node caps far lower anyway (arm_type.yaml joint_vel). Efforts: upstream's = Anvil's (40, 40, 27, 27, 7, 7, 7).
_V = (10.47, 10.47, 3.77, 3.77, 12.57, 12.57, 12.57)
_LIM = {
    "left": [(-3.4907, 1.3963), (-3.3161, 0.1745), (-1.570796, 1.570796), (0.0, 2.443461), (-1.570796, 1.570796),
             (-0.785398, 1.22173), (-1.570796, 1.570796)],
    "right": [(-1.3963, 3.4907), (-0.1745, 3.3161), (-1.570796, 1.570796), (0.0, 2.443461), (-1.570796, 1.570796),
              (-1.22173, 0.785398), (-1.570796, 1.570796)],
}
LIMITS = {side: {f"joint{k + 1}": (lo, hi, _V[k]) for k, (lo, hi) in enumerate(v)} for side, v in _LIM.items()}


def _f(v) -> str:
    return " ".join(f"{float(x):.9g}" for x in v)


def _inertial(parent, mass: float, com, ixx, iyy, izz) -> None:
    i = ET.SubElement(parent, "inertial")
    ET.SubElement(i, "origin", xyz=_f(com), rpy="0 0 0")
    ET.SubElement(i, "mass", value=f"{mass:.9g}")
    ET.SubElement(i, "inertia", ixx=f"{ixx:.9g}", ixy="0", ixz="0", iyy=f"{iyy:.9g}", iyz="0", izz=f"{izz:.9g}")


def gripper(robot: ET.Element, side: str) -> None:
    """Anvil's gripper (``gripper/anvil_gripper_<side>.urdf``: end_link and the fingers) on link7, end_link
    END_FROM_J7 below the joint-7 axis, x along the flange's -z."""
    j = ET.SubElement(robot, "joint", name="end_joint", type="fixed")
    ET.SubElement(j, "origin", xyz=_f([0, 0, -END_FROM_J7]), rpy=_f([0, math.pi / 2, 0]))   # x -> flange -z
    ET.SubElement(j, "parent", link="link7")
    ET.SubElement(j, "child", link="end_link")
    frag = ET.parse(GRIPPER / f"anvil_gripper_{side}.urdf").getroot()
    for el in frag:
        if el.tag not in ("link", "joint"):
            continue
        for m in el.iter("mesh"):
            m.set("filename", "../gripper/" + m.get("filename"))
        robot.append(el)


def scaled_stl(src: Path, dst: Path, scale) -> None:
    """A binary STL with ``scale`` (per axis) baked in: vertices and normals scaled (normals renormalised), each
    triangle's winding reversed when the scale mirrors (an odd number of negative factors), so its normals stay outward."""
    s = [float(v) for v in scale]
    data = src.read_bytes()
    (n,) = struct.unpack_from("<I", data, 80)
    if len(data) != 84 + 50 * n:
        raise ValueError(f"{src}: not a binary STL ({len(data)} bytes for {n} triangles)")
    flip = (s[0] * s[1] * s[2]) < 0
    out = bytearray(data[:84])
    for i in range(n):
        f = struct.unpack_from("<12fH", data, 84 + 50 * i)
        nx, ny, nz = (f[k] / s[k] if s[k] else 0.0 for k in range(3))      # normals: the inverse transpose
        ln = math.sqrt(nx * nx + ny * ny + nz * nz) or 1.0
        v = [[f[3 + 3 * j + k] * s[k] for k in range(3)] for j in range(3)]
        if flip:
            v[1], v[2] = v[2], v[1]
        out += struct.pack("<12fH", nx / ln, ny / ln, nz / ln, *v[0], *v[1], *v[2], f[12])
    dst.write_bytes(bytes(out))


def arm(src: ET.Element, side: str, mesh_dir: Path, upstream: Path) -> ET.Element:
    px = f"openarm_{side}_"
    robot = ET.Element("robot", name=f"openarm_v2_{side}_arm")
    links = {lk.get("name"): lk for lk in src.findall("link")}
    for n in LINKS:
        up = links[px + n]
        lk = ET.SubElement(robot, "link", name=n)
        lk.append(up.find("inertial"))
        col = up.find("collision/geometry/mesh")
        if col is not None:
            f = col.get("filename").replace("package://openarm_description/", "")
            name = Path(f).name
            scale = (col.get("scale") or "1 1 1").split()
            if [float(v) for v in scale] == [1.0, 1.0, 1.0]:
                shutil.copyfile(upstream / f, mesh_dir / name)
            else:                                    # upstream's mirrored left links: the scale baked in
                name = f"{side}_{name}"
                scaled_stl(upstream / f, mesh_dir / name, scale)
            o = up.find("collision/origin")
            for tag in ("visual", "collision"):
                g = ET.SubElement(lk, tag)
                ET.SubElement(g, "origin", xyz=o.get("xyz"), rpy=o.get("rpy"))
                ET.SubElement(ET.SubElement(g, "geometry"), "mesh", filename=f"../meshes/collision/{name}")
    lk7 = ET.SubElement(robot, "link", name="link7")
    _inertial(lk7, 1e-3, [0, 0, 0], 1e-7, 1e-7, 1e-7)                       # the flange: massless upstream
    for tag in ("visual", "collision"):
        g = ET.SubElement(lk7, tag, name="flange_adapter")
        ET.SubElement(g, "origin", xyz=_f(ADAPTER[0]), rpy="0 0 0")
        ET.SubElement(ET.SubElement(g, "geometry"), "box", size=_f(ADAPTER[1]))
        if tag == "visual":
            ET.SubElement(g, "material", name="flange_adapter").append(ET.Element("color", rgba="0.88 0.89 0.9 1"))
    for k in range(1, 8):
        up = src.find(f"joint[@name='{px}joint{k}']")
        j = ET.SubElement(robot, "joint", name=f"joint{k}", type=up.get("type"))
        o = up.find("origin")
        ET.SubElement(j, "origin", xyz=o.get("xyz"), rpy=o.get("rpy"))
        ET.SubElement(j, "parent", link=up.find("parent").get("link")[len(px):])
        ET.SubElement(j, "child", link="link7" if k == 7 else up.find("child").get("link")[len(px):])
        ET.SubElement(j, "axis", xyz=up.find("axis").get("xyz"))
        lo, hi, vel = LIMITS[side][f"joint{k}"]
        ET.SubElement(j, "limit", lower=f"{lo:.9g}", upper=f"{hi:.9g}", effort=up.find("limit").get("effort"),
                      velocity=f"{vel:.9g}")
    gripper(robot, side)
    return robot


def main(upstream: str) -> None:
    upstream = Path(upstream)
    src = ET.parse(upstream / EXAMPLE).getroot()
    mesh_dir = HERE / "meshes" / "collision"
    mesh_dir.mkdir(parents=True, exist_ok=True)
    for side in ("left", "right"):
        r = arm(src, side, mesh_dir, upstream)
        ET.indent(r, space="  ")
        head = (f"<?xml version=\"1.0\"?>\n<!-- OpenArm v2.0 {side} arm (enactic/openarm_description, Apache-2.0; "
                "README.md) with the Anvil OpenArm 2.0's joint ranges (J1: Enactic's window) and Anvil's Customizable "
                "Gripper. GENERATED by build_urdf.py: do not edit. -->\n")
        (HERE / "urdf" / f"openarm_v2_{side}_arm.urdf").write_text(head + ET.tostring(r, encoding="unicode") + "\n")
        print("wrote", side)


if __name__ == "__main__":
    main(sys.argv[1])
